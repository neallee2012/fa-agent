#!/usr/bin/env python3
"""Export the files tracked at a checkout's HEAD, with identifiers replaced, for the public repo.

Usage:  python scrub_export.py --src <checkout> --out <new or empty dir> --mapping <mapping.json> [--plain]

Content comes from the HEAD tree (git ls-tree + cat-file), never the worktree, so local edits, untracked files
and core.autocrlf do not reach the export. --plain copies the same files without replacements; verify_export.py
uses that copy as the hash-safety baseline. Text (UTF-8) files get every mapping.json replacement; binary files
are copied byte for byte. The process prints counts only, never values.

mapping.json (generated by discover.py from review.json; holds original values, so it is excluded):
  guids                 {original GUID (lowercase): placeholder}; hyphenated and 32-hex forms are replaced
  guid_prefix_scrub     also replace bounded 8-hex prefixes of those GUIDs and of truncated_prefixes
  truncated_prefixes    [8-hex prefixes whose full GUID is not in the repo]
  keep_guids            {public GUID: reason}; the residual sweep ignores them
  synthetic_guid_sha256 [sha256 of reviewed synthetic / test GUIDs]; with the placeholders and keep_guids,
                        the only GUIDs verify lets into the export
  rules                 [{id, category, type: literal|regex, find, replace, ignore_case?, bounded?,
                          verify_absent?, verify_ignore_case?, verify_absent_regex?, drops_tokens?}]
                        drops_tokens: the match removes a span (private-repo URLs), so verify does not require
                        hex/base64 tokens there to survive; groups the replacement keeps (link text) stay checked
  gitleaks_known_false_positives  [{rule (gitleaks RuleID), file (exact path), count?, why}]; no wildcards,
                        and more than `count` findings for one pair fail
  residual_allow        [{pattern (regex over "<kind>:<value>"), why}]
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path
import subprocess

# The only exclusion list. The scrub files hold original values. Workflows are left out as a whole: pushing
# anything under .github/workflows/ needs the Workflows permission, which the Contents-only token lacks, and
# public-sync / deploy-staging only work against the private stage anyway.
EXCLUDED_PATHS = frozenset({
    "scripts/public_export/mapping.json",
    "scripts/public_export/review.json",
    "scripts/public_export/candidates.txt",
})
EXCLUDED_PREFIXES = (".claude/", ".github/workflows/")

GUID = r"[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}"
GUID_RE = re.compile(rf"(?<![0-9A-Za-z]){GUID}(?![0-9A-Za-z])")
TOKEN_CHARS = re.compile(r"[A-Za-z0-9+=]")  # "/" splits paths; base64 runs stay long enough to flag
HEX_RE = re.compile(r"^[0-9a-fA-F]+$")
GIT_ENV = {**os.environ, "GIT_OPTIONAL_LOCKS": "0"}


def is_excluded(rel: str) -> bool:
    return rel in EXCLUDED_PATHS or rel.startswith(EXCLUDED_PREFIXES)


def guid_sha256(guid: str) -> str:
    """How review.json lists reviewed synthetic GUIDs: sha256 of the lowercase hyphenated form."""
    return hashlib.sha256(guid.lower().encode("ascii")).hexdigest()


def is_synthetic(guid: str) -> bool:
    """Placeholder-looking GUIDs (few distinct digits, repeated groups) are not reviewed."""
    g = guid.lower()
    h = g.replace("-", "")
    return (len(set(h)) <= 5 or "0000-0000" in g or "123456789" in h or "abcdefab" in h
            or sum(1 for grp in g.split("-")[1:] if len(set(grp)) == 1) >= 2)


def git(src: Path, *args: str, stdin: bytes | None = None) -> bytes:
    return subprocess.run(["git", "-C", str(src), *args], check=True, capture_output=True,
                          input=stdin, env=GIT_ENV).stdout


def head_files(src: Path) -> dict[str, tuple[str, bytes]]:
    """{path: (mode, bytes)} for every blob tracked at HEAD and not excluded."""
    entries = []
    for entry in git(src, "ls-tree", "-r", "-z", "--full-tree", "HEAD").decode("utf-8").split("\0"):
        if not entry:
            continue
        meta, rel = entry.split("\t", 1)
        mode, kind, sha = meta.split()
        if kind == "blob" and not is_excluded(rel):
            entries.append((rel, mode, sha))
    shas = sorted({sha for _, _, sha in entries})
    blobs: dict[str, bytes] = {}
    if shas:
        out = git(src, "cat-file", "--batch", stdin=("\n".join(shas) + "\n").encode())
        pos = 0
        for sha in shas:
            header_end = out.index(b"\n", pos)
            size = int(out[pos:header_end].split()[2])
            blobs[sha] = out[header_end + 1:header_end + 1 + size]
            pos = header_end + 1 + size + 1
    return {rel: (mode, blobs[sha]) for rel, mode, sha in sorted(entries)}


def decode_text(data: bytes) -> str | None:
    if b"\0" in data[:8192]:
        return None
    try:
        return data.decode("utf-8")
    except UnicodeDecodeError:
        return None


def looks_like_hash(token: str) -> bool:
    if len(token) >= 32 and HEX_RE.match(token):
        return True
    return len(token) >= 24 and (any(c in token for c in "+/=") or bool(
        re.search(r"[a-z]", token) and re.search(r"[A-Z]", token) and re.search(r"[0-9]", token)))


class Scrubber:
    def __init__(self, mapping: dict):
        self.counts: Counter = Counter()
        self.cat_counts: Counter = Counter()
        self.hash_like: list[tuple[str, int, str]] = []
        self.file_counts: dict[str, Counter] = defaultdict(Counter)
        guids = {k.lower(): v for k, v in mapping["guids"].items()}
        hexless = {k.replace("-", ""): v.replace("-", "") for k, v in guids.items()}
        self.passes: list[tuple[str, str, re.Pattern, object]] = []
        if guids:
            alt = "|".join(re.escape(g) for g in sorted(guids, key=len, reverse=True))
            self.passes.append(("guid", "guid", re.compile(rf"(?<![0-9A-Za-z])(?:{alt})(?![0-9A-Za-z])", re.I),
                                lambda m: guids[m.group(0).lower()]))
            alt2 = "|".join(re.escape(g) for g in hexless)
            self.passes.append(("guid-nohyphen", "guid", re.compile(rf"(?<![0-9A-Za-z])(?:{alt2})(?![0-9A-Za-z])", re.I),
                                lambda m: hexless[m.group(0).lower()]))
        for rule in mapping["rules"]:
            flags = re.I if rule.get("ignore_case") else 0
            if rule["type"] == "literal":
                pat = re.escape(rule["find"])
                if rule.get("bounded", True):
                    pat = rf"(?<![A-Za-z0-9]){pat}(?![A-Za-z0-9])"
                self.passes.append((rule["id"], rule["category"], re.compile(pat, flags),
                                    lambda m, r=rule["replace"]: r))
            else:
                self.passes.append((rule["id"], rule["category"], re.compile(rule["find"], flags), rule["replace"]))
        prefixes = sorted({g[:8] for g in guids} | {p.lower() for p in mapping.get("truncated_prefixes", [])})
        if mapping.get("guid_prefix_scrub") and prefixes:
            self.passes.append(("guid-prefix", "guid-prefix",
                                re.compile(rf"(?<![0-9A-Za-z])(?:{'|'.join(prefixes)})(?![0-9A-Za-z])", re.I),
                                lambda m: "00000000"))

    def _check(self, text: str, m: re.Match, rel: str, rule_id: str) -> None:
        s, e = m.start(), m.end()
        while s > 0 and TOKEN_CHARS.match(text[s - 1]):
            s -= 1
        while e < len(text) and TOKEN_CHARS.match(text[e]):
            e += 1
        left = text[s:m.start()].rsplit("=", 1)[-1]  # base64 "=" is only trailing padding, so "key=" is a separator
        right = text[m.end():e]
        if (left or right) and looks_like_hash((left + m.group(0) + right).replace("-", "")):
            self.hash_like.append((rel, text.count("\n", 0, m.start()) + 1, rule_id))

    def scrub(self, text: str, rel: str) -> str:
        for rule_id, cat, rx, repl in self.passes:
            current, hits = text, 0

            def sub(m: re.Match, repl=repl, rule_id=rule_id) -> str:
                nonlocal hits
                hits += 1
                self._check(current, m, rel, rule_id)
                return repl(m) if callable(repl) else m.expand(repl)

            text = rx.sub(sub, text)
            if hits:
                self.counts[rule_id] += hits
                self.cat_counts[cat] += hits
                self.file_counts[rel][rule_id] += hits
        return text


def export(src: Path, out: Path, mapping: dict, plain: bool) -> Scrubber:
    if out.exists() and any(out.iterdir()):
        raise SystemExit(f"--out must be a new or empty directory: {out}")
    out.mkdir(parents=True, exist_ok=True)
    scrubber = Scrubber(mapping)
    binaries, text_count = [], 0
    for rel, (mode, data) in head_files(src).items():
        dest = out / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        text = decode_text(data)
        if text is None:
            binaries.append(rel)
        else:
            text_count += 1
            if not plain:
                new = scrubber.scrub(text, rel)
                if new != text:
                    data = new.encode("utf-8")
        dest.write_bytes(data)
        if mode == "100755":
            dest.chmod(0o755)
    print(f"{'plain' if plain else 'scrub'}: {text_count} text files, {len(binaries)} binary (copied unchanged)")
    if not plain:
        print(f"changed files: {len(scrubber.file_counts)}")
        print("replacements by category:", json.dumps(dict(sorted(scrubber.cat_counts.items()))))
        print(f"hash-like tokens touched: {len(scrubber.hash_like)}")
        for rel, line, rule_id in scrubber.hash_like:
            print(f"    HASH-LIKE {rel}:{line} rule {rule_id}")
    return scrubber


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--src", required=True, help="git checkout to export (its HEAD commit)")
    ap.add_argument("--out", required=True, help="new or empty output directory outside --src")
    ap.add_argument("--mapping", required=True)
    ap.add_argument("--plain", action="store_true", help="copy without replacements (hash-safety baseline)")
    args = ap.parse_args(argv)
    src, out = Path(args.src).resolve(), Path(args.out).resolve()
    if out == src or src in out.parents:
        raise SystemExit("--out must not be inside --src")
    mapping = json.loads(Path(args.mapping).read_text(encoding="utf-8"))
    export(src, out, mapping, args.plain)
    return 0


if __name__ == "__main__":
    sys.exit(main())
